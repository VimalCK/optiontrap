-- Trade automation (see shared/automation.js).

-- Each user's automation configuration, one row per user. The shape is
-- checked by parseAutomationConfig before it is stored.
CREATE TABLE IF NOT EXISTS automation_configs (
  user_id    TEXT PRIMARY KEY,
  config     JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One row per automated trade, from selection to completion. stage is the
-- latest stage; the full history is in auto_trade_events. position_id links
-- the paper position once the trade is executed.
CREATE TABLE IF NOT EXISTS auto_trades (
  id               TEXT PRIMARY KEY,
  user_id          TEXT NOT NULL,
  horizon          TEXT NOT NULL CHECK (horizon IN ('intraday', 'positional')),
  kind             TEXT NOT NULL CHECK (kind IN ('stock', 'stock-option', 'stock-future', 'index-option', 'index-future')),
  mode             TEXT NOT NULL CHECK (mode IN ('paper', 'live')),
  tradingsymbol    TEXT NOT NULL,
  instrument_token BIGINT NOT NULL,
  side             TEXT NOT NULL CHECK (side IN ('BUY', 'SELL')),
  quantity         BIGINT NOT NULL CHECK (quantity > 0),
  stage            TEXT NOT NULL CHECK (stage IN ('selected', 'validated', 'rejected', 'executed', 'closed')),
  reason           TEXT,
  position_id      TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The page lists a user's trades newest first.
CREATE INDEX IF NOT EXISTS auto_trades_user_created_idx ON auto_trades (user_id, created_at DESC);
-- The trade monitor will look up a user's trades still in progress.
CREATE INDEX IF NOT EXISTS auto_trades_user_open_idx ON auto_trades (user_id, stage) WHERE stage NOT IN ('rejected', 'closed');

-- Every stage a trade passed through, with when and why.
CREATE TABLE IF NOT EXISTS auto_trade_events (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auto_trade_id TEXT NOT NULL REFERENCES auto_trades (id) ON DELETE CASCADE,
  stage         TEXT NOT NULL CHECK (stage IN ('selected', 'validated', 'rejected', 'executed', 'closed')),
  at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  detail        JSONB
);

CREATE INDEX IF NOT EXISTS auto_trade_events_trade_idx ON auto_trade_events (auto_trade_id, at);
