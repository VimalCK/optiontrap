-- Daily candles for watchlist stocks (and NIFTY 50 as the market reference),
-- one row per stock per trading day. Completed sessions only: today's candle
-- is stored after the 15:45 IST close.
CREATE TABLE IF NOT EXISTS stock_daily_candles (
  instrument_token BIGINT NOT NULL,
  date             TEXT NOT NULL,            -- YYYY-MM-DD (IST)
  open             DOUBLE PRECISION NOT NULL,
  high             DOUBLE PRECISION NOT NULL,
  low              DOUBLE PRECISION NOT NULL,
  close            DOUBLE PRECISION NOT NULL,
  volume           BIGINT NOT NULL,
  PRIMARY KEY (instrument_token, date)
);

-- Sync bookkeeping per stock: how far its candles go and when Kite was last asked.
CREATE TABLE IF NOT EXISTS stock_candle_sync (
  instrument_token BIGINT PRIMARY KEY,
  last_date        TEXT,                     -- newest stored candle
  checked_at       BIGINT NOT NULL,          -- epoch ms of the last Kite request
  full_fetched_at  BIGINT NOT NULL           -- epoch ms of the last full-history fetch
);

-- Latest scan per stock, shown in the watchlist's Setups column.
CREATE TABLE IF NOT EXISTS stock_setup_scans (
  instrument_token BIGINT PRIMARY KEY,
  scan_date        TEXT NOT NULL,            -- date of the candle the scan used
  summary          JSONB NOT NULL,
  updated_at       BIGINT NOT NULL
);

-- Every setup the daily scan found, with its outcome once price hits the
-- target or stop, or the holding window runs out.
CREATE TABLE IF NOT EXISTS stock_setup_signals (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instrument_token   BIGINT NOT NULL,
  tradingsymbol      TEXT NOT NULL,
  signal_date        TEXT NOT NULL,
  setup_type         TEXT NOT NULL,
  direction          TEXT NOT NULL,          -- buy | sell
  entry              DOUBLE PRECISION NOT NULL,
  stop               DOUBLE PRECISION NOT NULL,
  target             DOUBLE PRECISION NOT NULL,
  status             TEXT NOT NULL DEFAULT 'open',  -- open | target | stop | expired
  resolved_date      TEXT,
  sessions_held      INTEGER NOT NULL DEFAULT 0,
  max_favorable_pct  DOUBLE PRECISION,
  max_adverse_pct    DOUBLE PRECISION,
  created_at         BIGINT NOT NULL,
  UNIQUE (instrument_token, signal_date, setup_type)
);

CREATE INDEX IF NOT EXISTS idx_stock_setup_signals_open ON stock_setup_signals(instrument_token) WHERE status = 'open';
