CREATE TABLE IF NOT EXISTS trade_setup_signals (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         TEXT NOT NULL,
  scrip           TEXT NOT NULL,
  signal_date     TEXT NOT NULL,
  expiry          TEXT,
  strike          DOUBLE PRECISION NOT NULL,
  option_type     TEXT NOT NULL,
  action          TEXT NOT NULL,
  status          TEXT NOT NULL,
  entry_premium   DOUBLE PRECISION,
  spot_price      DOUBLE PRECISION,
  details         JSONB NOT NULL DEFAULT '{}'::jsonb,
  outcome_price   DOUBLE PRECISION,
  outcome_date    TEXT,
  outcome_return  DOUBLE PRECISION,
  outcome_status  TEXT,
  created_at      TEXT NOT NULL DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE(user_id, scrip, signal_date, expiry, strike, option_type, action)
);

CREATE INDEX IF NOT EXISTS idx_trade_setup_signals_user_date
  ON trade_setup_signals(user_id, signal_date DESC);
